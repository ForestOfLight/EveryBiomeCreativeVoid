"""Regolith filter: generates one dimension definition per vanilla biome.

Fetches the vanilla biome list from Mojang's bedrock-samples metadata and writes
BP/dimensions/<biome>.json for each biome, based on data/dimension_template.json.
Also writes BP/scripts/biomes.js, which exports the list of biomes and their
dimension identifiers so scripts can use them during early execution.

Optional filter settings:
    "url": override the biome list URL.
"""
import copy
import json
import os
import sys
import urllib.request

BIOMES_URL = "https://raw.githubusercontent.com/Mojang/bedrock-samples/refs/heads/main/metadata/vanilladata_modules/mojang-biomes.json"
TEMPLATE_PATH = os.path.join("data", "dimension_template.json")
OUTPUT_DIR = os.path.join("BP", "dimensions")
SCRIPT_PATH = os.path.join("BP", "scripts", "biomes.js")


def load_settings():
    if len(sys.argv) > 1 and sys.argv[1].strip():
        return json.loads(sys.argv[1])
    return {}


def fetch_biomes(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        data = json.load(response)
    return sorted(item["name"] for item in data["data_items"])


def dimension_id(namespace, biome):
    return f"{namespace}:{biome.split(':', 1)[1]}"


def build_dimension(template, namespace, biome):
    dimension = copy.deepcopy(template)
    body = dimension["minecraft:dimension"]
    body["description"]["identifier"] = dimension_id(namespace, biome)
    body["components"]["minecraft:default_biome"]["biome"] = biome
    return dimension


def write_biome_script(namespace, biomes):
    entries = [{"biomeId": biome, "dimensionId": dimension_id(namespace, biome)} for biome in biomes]
    os.makedirs(os.path.dirname(SCRIPT_PATH), exist_ok=True)
    with open(SCRIPT_PATH, "w", encoding="utf-8") as f:
        f.write("// Generated by the build_dimension_definitions filter. Do not edit.\n")
        f.write(f"export const biomes = Object.freeze({json.dumps(entries, indent=4)});\n")


def main():
    settings = load_settings()
    url = settings.get("url", BIOMES_URL)

    with open(TEMPLATE_PATH, encoding="utf-8") as f:
        template = json.load(f)
    namespace = template["minecraft:dimension"]["description"]["identifier"].split(":", 1)[0]

    try:
        biomes = fetch_biomes(url)
    except Exception as e:
        sys.exit(f"Failed to fetch biome list from {url}: {e}")

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for biome in biomes:
        dimension = build_dimension(template, namespace, biome)
        output_path = os.path.join(OUTPUT_DIR, f"{biome.split(':', 1)[1]}.json")
        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(dimension, f, indent=4)
            f.write("\n")

    write_biome_script(namespace, biomes)

    print(f"Generated {len(biomes)} dimension definitions in {OUTPUT_DIR} and biome list in {SCRIPT_PATH}")


if __name__ == "__main__":
    main()
